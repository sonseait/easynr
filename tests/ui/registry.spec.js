const {test, expect} = require('@playwright/test');
async function login(page) {
 await page.goto('/');
 await page.getByLabel('Admin password').fill('incorrect-password');
 await page.getByRole('button', {name: 'Sign in', exact: true}).click();
 await expect(page.getByRole('status')).toContainText('Incorrect password');
 await page.getByLabel('Admin password').fill('browser-test-password');
 await page.getByRole('button', {name: 'Sign in', exact: true}).click();
 await expect(page.getByRole('heading', {name: 'Packages', exact: true})).toBeVisible();
}
test('live console: session, package, one-time token, routes and logout', async ({page}) => {
 const errors = []; page.on('pageerror', e => errors.push(e.message));
 await login(page);
 await page.reload();
 await expect(page.getByRole('heading', {name: 'Packages', exact: true})).toBeVisible();
 await page.getByRole('button', {name: '@demo/hello', exact: true}).click();
 const details = page.getByRole('dialog');
 await expect(details.getByRole('cell', {name: 'local', exact: true})).toBeVisible();
 await expect(details.getByRole('cell', {name: '1.0.0', exact: true})).toBeVisible();
 const [setTag, removeTag, clearPackageCache, deletePackage] = await Promise.all(
  ['Set tag', 'Remove local tag latest', 'Clear remote cache', 'Delete local package'].map(name => details.getByRole('button', {name, exact: true}).boundingBox())
 );
 expect(removeTag.y - (setTag.y + setTag.height)).toBeGreaterThanOrEqual(6);
 expect(clearPackageCache.y - (removeTag.y + removeTag.height)).toBeGreaterThanOrEqual(6);
 expect(Math.max(deletePackage.x - (clearPackageCache.x + clearPackageCache.width), deletePackage.y - (clearPackageCache.y + clearPackageCache.height))).toBeGreaterThanOrEqual(6);
 page.once('dialog', dialog => dialog.dismiss());
 await details.getByRole('button', {name: 'Delete local package', exact: true}).click();
 await details.getByRole('button', {name: 'Close', exact: true}).click();
 await page.getByRole('button', {name: 'Tokens', exact: true}).click();
 const unsafeName = '<img src=x onerror=alert(1)> ' + test.info().project.name;
 await page.getByLabel('Token name').fill(unsafeName);
 await page.getByLabel('Grants: one package and permission per line').fill('@demo/* write\n* read');
 await page.getByRole('button', {name: 'Create token', exact: true}).click();
 const tokenDialog = page.getByRole('dialog');
 const secret = await tokenDialog.getByLabel('Token secret').inputValue();
 expect(secret).toMatch(/^enr_/);
 const tokenLayout = await tokenDialog.getByLabel('Token secret').evaluate(n => ({width: n.clientWidth, available: n.parentElement.clientWidth, height: n.clientHeight, contentHeight: n.scrollHeight, contentWidth: n.scrollWidth}));
 expect(tokenLayout.width).toBeGreaterThanOrEqual(tokenLayout.available - 2);
 expect(tokenLayout.contentHeight).toBeLessThanOrEqual(tokenLayout.height);
 expect(tokenLayout.contentWidth).toBeLessThanOrEqual(tokenLayout.width);
 await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable: true, value: {writeText: async value => { window.copiedToken = value; }}}));
 await tokenDialog.getByRole('button', {name: 'Copy token', exact: true}).click();
 await expect(tokenDialog.getByRole('status')).toHaveText('Token copied.');
 expect(await page.evaluate(() => window.copiedToken)).toBe(secret);
 await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', {configurable: true, value: undefined}));
 await tokenDialog.getByRole('button', {name: 'Copy token', exact: true}).click();
 await expect(tokenDialog.getByRole('status')).toContainText('copy it manually');
 const selection = await tokenDialog.getByLabel('Token secret').evaluate(n => n.selectionEnd - n.selectionStart);
 expect(selection).toBe(secret.length);
 await tokenDialog.screenshot({path: test.info().outputPath('token-dialog.png')});
 await tokenDialog.getByRole('button', {name: 'Close', exact: true}).click();
 await expect(page.getByText(unsafeName, {exact: true})).toBeVisible();
 expect(await page.locator('img').count()).toBe(0);
 expect(await page.locator('body').textContent()).not.toContain(secret);
 const metadata = await page.request.get('/browser-cache', {headers: {Authorization: 'Bearer ' + secret}});
 expect(metadata.ok()).toBeTruthy();
 const packument = await metadata.json();
 const tarball = await page.request.get(packument.versions['1.0.0'].dist.tarball, {headers: {Authorization: 'Bearer ' + secret}});
 expect(tarball.ok()).toBeTruthy();
 await page.getByRole('button', {name: 'Packages', exact: true}).click();
 await expect(page.getByRole('button', {name: 'browser-cache', exact: true})).toHaveCount(0);
 const listedPackages = await page.request.get('/api/packages');
 expect((await listedPackages.json()).items.map(p => p.name)).toEqual(['@demo/hello']);
 const cache = page.getByRole('region', {name: 'Cache statistics'});
 await expect(cache.locator('div').filter({has: page.locator('dt', {hasText: 'Cached packages'})}).locator('dd')).toHaveText('1');
 await expect(cache.locator('div').filter({has: page.locator('dt', {hasText: 'Cache size'})}).locator('dd')).toHaveText('22 B');
 await expect(page.getByRole('button', {name: 'Refresh', exact: true})).toHaveCount(0);
 page.once('dialog', dialog => dialog.dismiss());
 await cache.getByRole('button', {name: 'Clear cache', exact: true}).click();
 await expect(cache.locator('dd').first()).toHaveText('1');
 page.once('dialog', dialog => dialog.accept());
 await cache.getByRole('button', {name: 'Clear cache', exact: true}).click();
 await expect(cache.locator('dd').first()).toHaveText('0');
 await expect(cache.locator('dd').last()).toHaveText('0 B');
 await expect(page.getByRole('button', {name: '@demo/hello', exact: true})).toBeVisible();
 await page.getByRole('button', {name: 'Tokens', exact: true}).click();
 const tokenRow = page.locator('.row').filter({has: page.getByText(unsafeName, {exact: true})});
 page.once('dialog', dialog => dialog.accept());
 await tokenRow.getByRole('button', {name: 'Revoke', exact: true}).click();
 await expect(page.getByText(unsafeName, {exact: true})).toHaveCount(0);
 await page.getByRole('button', {name: 'Upstreams', exact: true}).click();
 const fixtureRow = page.locator('.row').filter({has: page.getByText('Fixture (fixture)', {exact: true})});
 await fixtureRow.getByRole('button', {name: 'Test', exact: true}).click();
 await expect(fixtureRow).toContainText('Upstream reachable (HTTP 200).');
 await page.getByRole('button', {name: 'Add upstream', exact: true}).click();
 const upstream = page.getByRole('dialog');
 const id = 'ui-' + test.info().project.name;
 await upstream.getByLabel('ID', {exact: true}).fill(id);
 await upstream.getByLabel('Display name').fill('Browser upstream');
 await upstream.getByLabel('Registry URL').fill('https://registry.example.com');
 await upstream.getByLabel('Bearer token (empty keeps existing, - clears)').fill('hidden-upstream-secret');
 await upstream.getByRole('button', {name: 'Save upstream', exact: true}).click();
 await expect(upstream).toHaveCount(0);
 await expect(page.getByRole('heading', {name: 'Upstreams', exact: true})).toBeVisible();
 await expect(page.getByLabel('Scope (@team) or * for default')).toHaveCount(0);
 await page.getByRole('button', {name: 'Routes', exact: true}).click();
 await expect(page.getByRole('heading', {name: 'Routes', exact: true})).toBeVisible();
 await expect(page.getByRole('button', {name: 'Add upstream', exact: true})).toHaveCount(0);
 await page.getByLabel('Scope (@team) or * for default').fill('@browser');
 await page.getByLabel('Upstream', {exact: true}).selectOption(id);
 await page.getByRole('button', {name: 'Save route', exact: true}).click();
 await expect(page.getByText('@browser → ' + id, {exact: true})).toBeVisible();
 await expect(page.getByRole('button', {name: 'Routes', exact: true})).toHaveAttribute('aria-pressed', 'true');
 await page.getByRole('button', {name: 'Upstreams', exact: true}).click();
 await expect(page.getByRole('heading', {name: 'Upstreams', exact: true})).toBeVisible();
 await page.getByRole('button', {name: 'Routes', exact: true}).click();
 await expect(page.getByText('@browser → ' + id, {exact: true})).toBeVisible();
 expect(await page.locator('body').textContent()).not.toContain('hidden-upstream-secret');
 const route = page.locator('.row').filter({hasText: '@browser → ' + id});
 page.once('dialog', dialog => dialog.accept()); await route.getByRole('button', {name: 'Remove', exact: true}).click();
 await expect(page.getByText('@browser → ' + id, {exact: true})).toHaveCount(0);
 await page.getByRole('button', {name: 'Sign out', exact: true}).click();
 await expect(page.getByLabel('Admin password')).toBeVisible();
 expect(errors).toEqual([]);
});
